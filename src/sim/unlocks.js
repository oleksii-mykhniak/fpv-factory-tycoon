// Одні двері для всіх панелей (Стадія 11 / D1).
//
// Питання «чи гравцеві вже показували цю річ» ставлять чотири різні місця —
// шафа (трек поліпшень), дошка найму (роль), картка комплекту (рядок Mk) і
// панель підвищення. До Стадії 11 відповідь на нього мала рівно одна з них
// (`trackIntroduced`), а решта показувала все й одразу: гараж відкривався
// чотирма ролями в списку, магазин — другою ціною на кожній картці.
//
// Правило тут одне на всіх, і воно те саме, що вже працювало для треків:
//
//   1. ланцюг пройшов крок, який цю річ `opens` — видно;
//   2. це те, що ланцюг попросить НАСТУПНИМ — видно теж;
//   3. інакше — сховано.
//
// Друге правило не косметика, а те, без чого панель, у яку гравця щойно
// послали, зустрічає його порожньою. Саме воно колись і врятувало шафу.
//
// Жодного нового поля в сейві: `opens` — властивість кроку, індекс активного
// кроку виводиться зі стану (див. quests.js), тож «що відкрито» лишається
// функцією від того, що гравець зробив.

import { QUEST_CHAIN, questIndex } from './quests.js'

// Наступна річ ЦЬОГО ЖЕ роду, яку ланцюг збирається ввести.
//
// Рід (`track` / `role` / `mk` / `panel`) — не дрібниця, а те, від чого
// залежить, чи спорожніє панель. Правило «наступне взагалі» дало б, скажімо,
// найм кур'єра — і шафа поруч із ним стояла б порожня, бо трек, який ланцюг
// попросить після, ще «не введений». Кожна панель мусить бачити своє наступне.
//
// «Наступна» означає «наступна, яку тут узагалі можна отримати»: кроки, вже
// пройдені або безглузді в цій локації, пропускаються. Без цього правило
// вказувало б на річ, купити яку неможливо, — а панель лишалась би порожньою.
// Це не теоретична дірка: у квартирі з паяльником у стелі воно вказувало саме
// на паяльник, якого в списку вже нема.
function nextFeatureOfKind(game, kind) {
  for (let i = questIndex(game); i < QUEST_CHAIN.length; i++) {
    const step = QUEST_CHAIN[i]
    if (!step.opens?.startsWith(`${kind}:`)) continue
    if (step.moot?.(game) || step.done(game)) continue
    return step.opens
  }
  return null
}

// Чи гравцеві вже показували цю річ. `featureId` — те, що стоїть у `opens`
// кроку: `track:<id>`, `role:<id>`, `mk:<kitId>`, `panel:promote`.
export function featureIntroduced(game, featureId) {
  const at = QUEST_CHAIN.findIndex(s => s.opens === featureId)
  if (at < 0) return true                  // річ, якої ланцюг не згадує взагалі
  if (questIndex(game) >= at) return true

  // Гравець зробив це раніше, ніж ланцюг попросив. Без цієї умови правило
  // немонотонне: показ «наступного» — це ПРОГНОЗ, він їде далі, і річ, яку
  // гравець щойно купив на випередження, зникала б з панелі до того, як
  // ланцюг до неї дійде. Ловиться це рівно так: купив Mk II міні-дрона з
  // передоплати — і рядок Mk на його картці зник.
  if (QUEST_CHAIN[at].done(game)) return true

  return nextFeatureOfKind(game, featureId.split(':')[0]) === featureId
}

// Обгортка для шафи: трек — така сама річ, як роль чи Mk, просто в неї свій
// префікс. Лишається окремою назвою, бо так її читають три місця, які про
// префікси знати не мусять.
export function trackIntroduced(game, trackId) {
  return featureIntroduced(game, `track:${trackId}`)
}
