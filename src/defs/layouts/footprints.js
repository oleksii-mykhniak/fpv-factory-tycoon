// Слід предмета — та його частина, що СТОЇТЬ НА ЗЕМЛІ.
//
// Досі перешкодою був увесь прямокутник спрайта, і через це вибір був із двох
// поганих варіантів. Або предмет суцільний — і тоді дерево заввишки в півтора
// персонажа перегороджує двір смугою, у якій нема нічого, крім крони, тобто
// повітря. Або предмет наскрізний — і тоді крізь машину можна пройти. У дворі
// вибрали друге, і двір вийшов декорацією, по якій ходять як по підлозі.
//
// Правильна межа проходить не між «вулиця» і «кімната», а всередині самого
// малюнка: скільки в ньому ЗЕМЛІ, а скільки ВИСОТИ.
//
//   ліжко, ящик, піддон  — намальовані згори, увесь прямокутник лежить на
//                          підлозі. Слід = увесь прямокутник.
//   дерево, ліхтар       — намальовані збоку-згори, на землі стоїть стовбур,
//                          решта висить у повітрі. Слід = кілька відсотків.
//
// Тому таблиця ключується СПРАЙТОМ, а не місцем: у дерева той самий стовбур,
// де б воно не росло, і нове дерево в розкладці отримує правильну перешкоду
// саме тому, що ніхто про неї не думав.
//
// Частки — від намальованого прямокутника. Слід тулиться до НИЗУ спрайта й
// центрується по горизонталі: об'єкт стоїть на своїх ногах, а не висить
// посередині власної картинки.
//
// Спрайта немає в таблиці — крізь нього ходять (килим, картина, розмітка).
// Це і є заміна старому `solid`: прапорець при кожній розстановці повторював
// те саме рішення десятки разів і рано чи пізно розійшовся б сам із собою.

