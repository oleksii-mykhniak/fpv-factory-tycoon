// Прямокутник перешкоди для намальованого прямокутника `box` (у формі, яку
// віддає `rect()`: cx/cy + w/h + x/y). Повертає null для того, крізь що ходять.
export function footprintOf(sprite, box) {
  const spec = FOOTPRINTS[sprite]
  if (!spec) return null

  const w = box.w * spec.w
  const h = box.h * spec.h
  // Низ сліду збігається з низом спрайта — це і є «стоїть на землі».
  const cy = box.cy + box.h / 2 - h / 2
  return { cx: box.cx, cy, w, h, x: box.cx - w / 2, y: cy - h / 2 }
}
