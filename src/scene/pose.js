// Яку графіку показати персонажу з ШІ-аркушів — і чи дзеркалити її.
//
// Окремий файл, а не функція в character.js, з однієї причини: character.js
// тягне excalibur, а excalibur вимагає DOM. Тобто найважливіше рішення рига —
// «куди зараз дивиться людина» — у тестах було б недосяжним саме тому, що
// лежить поруч зі спрайтами. Тут воно чиста функція над числами, і його видно
// з Node.
//
// `facedAway` — пам'ять рига: куди персонаж дивився, коли ще рухався. У мить
// зупинки швидкість нульова й про напрямок не каже нічого, тому стан доводиться
// нести ззовні; функція його не зберігає, а повертає новий.
//
// vy > 0 — вниз по екрану (до глядача), vy < 0 — вгору (від глядача).
//
// `carrying` вмикає позу з руками вперед. Сама коробка в аркуші НЕ намальована —
// у грі в руках буває і коробка, і готовий дрон, і згорілий (`carrySpriteKey`),
// тож предмет кладе згори сцена. Запечений в арт ящик брехав би в двох випадках
// із трьох.
export function pickPose({
  moving, vx = 0, vy = 0, facingRight = true, facedAway = false, carrying = false,
  hasSide = false, hasIdleUp = false, hasUpCarry = false, sideFacesRight = false,
}) {
  if (!moving) {
    // Спиною стоїмо лише коли є чим: без окремого аркуша підстановка ходи
    // крутила б крок на місці, і це гірше за розворот до глядача.
    return { name: hasIdleUp && facedAway ? 'idleUp' : 'idle', flip: false, facedAway }
  }
  // Порівнюємо модулі, а не пороги: чистий горизонтальний хід не має
  // перемикати на вид ззаду через дрібне розштовхування в натовпі.
  if (Math.abs(vy) > Math.abs(vx)) {
    const away = vy < 0
    // Нести-поза намальована ЛИШЕ для ходи від глядача: там руки виставлені
    // вперед і порожні, тобто предмет у них кладе гра, а не аркуш. У решті
    // напрямків предмет лишається над головою — інакше його довелося б чіпляти
    // до фігури з опущеними руками.
    const carryAway = away && carrying && hasUpCarry
    return { name: carryAway ? 'upCarry' : away ? 'up' : 'down', flip: false, facedAway: away }
  }
  // Бічний хід — профіль, а не спина: спинившись після нього, персонаж
  // стоїть обличчям.
  return {
    name: hasSide ? 'side' : 'down',
    flip: hasSide && facingRight !== sideFacesRight,
    facedAway: false,
  }
}

// Де сидить предмет, який цей персонаж несе, — за назвою його пози.
//
// Тут, поруч із `pickPose`, і з тієї самої причини: це рішення читає лише
// напрямок погляду, а напрямок погляду вже вибрано вище. Розносити їх по
// різних файлах означало б виводити «куди дивиться людина» двічі.
//
// Три поля, і кожне відповідає на своє питання:
//
//   inHands  — на рівні пояса чи над головою. Над головою предмет опиняється
//   лише там, де пози немає взагалі (риг найманих робітників: чотири кадри без
//   жодного натяку на напрямок). Мати руки й не класти в них — гірше за
//   неточні руки.
//
//   behind   — ближче до камери чи далі за неї. Йдучи ВІД глядача, людина несе
//   предмет по той бік себе, і назовні видно самі краї; йдучи ДО глядача —
//   по цей, і предмет затуляє ноги. Переплутати ці два випадки — єдина
//   помилка розміщення, яку видно з першого погляду.
//
//   sideways — чи зсувати предмет уперед по ходу. У профіль руки виставлені
//   вбік від осі фігури, і предмет, залишений на осі, читається як такий, що
//   стирчить із живота.
//
// Аркуші ходьби (крім `upCarry`) намальовані з ОПУЩЕНИМИ руками, тож поки
// їх не перемалюють, предмет висить там, де руки мали б бути, а не там, де
// вони є. Це свідомий проміжний стан: коробка на поясі з неточними руками
// читається як ноша, коробка над головою не читається ніяк.
export function carryPlacement(pose) {
  if (!pose) return { inHands: false, behind: false, sideways: false }
  const away = pose === 'up' || pose === 'upCarry' || pose === 'idleUp'
  return { inHands: true, behind: away, sideways: pose === 'side' }
}
