// Скільки мілісекунд минуло з попереднього кадру, за подією 'preupdate'.
//
// В Excalibur 0.32 поле перейменували `delta` → `elapsed`, і код, який читав
// `evt.delta`, почав отримувати undefined. Мовчки: лічильник ставав NaN, а
// NaN >= FLOAT_MS — false, тобто «+$47» над скринькою не зникав НІКОЛИ, смужка
// таймера не наповнювалась, тост не гаснув. Одне місце на всі кадрові
// лічильники саме тому, що ця помилка не падає, а просто зупиняє час.
export const frameMs = (evt) => evt?.elapsed ?? evt?.delta ?? 16
