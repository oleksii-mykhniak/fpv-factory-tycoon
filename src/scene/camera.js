// Як камера доганяє персонажа — і чому не рушієвою стратегією.
//
// Було `camera.strategy.elasticToActor`. Її реалізація (excalibur 0.32,
// `ElasticToActorStrategy`) приймає `elapsed` і НЕ ВЖИВАЄ його:
//
//   const stretch = position.sub(focus).scale(elasticity)
//   cameraVel = cameraVel.add(stretch)
//   cameraVel = cameraVel.add(cameraVel.scale(-1).scale(friction))
//   focus = focus.add(cameraVel)
//
// Тобто пружина крокує РАЗ НА КАДР сталими числами, тоді як персонаж іде
// `vx * секунди`, тобто за часом. На 60 Гц, під які підбирались 0.20/0.28, це
// збігалось. На моніторі 144–165 Гц пружина отримує в 2.5 раза більше кроків
// на секунду, стає жорсткішою, ніж її гасить тертя, і починає перелітати ціль
// туди-сюди щокадру. На екрані світ дрібно смикається навколо персонажа — а на
// швидкості це видно як роздвоєння всієї картинки.
//
// Знайдено з повідомлення про «роздвоєння на широкому екрані»: широкий монітор
// на ПК майже завжди ще й високочастотний, тож симптом корелює з шириною, а
// причина — у частоті.
//
// Тут натомість експоненційне згладжування, і воно незалежне від частоти
// кадрів за побудовою: частка шляху, яку камера долає за `dt`, рахується з
// `dt`, а не з кількості викликів. Швидкість задана в 1/секунду, тож 165 кадрів
// по 6 мс дають рівно те саме, що 60 кадрів по 16.7 мс.
//
// Пружності (перельоту) тут немає навмисно. Її й не було: 0.20 < 0.28 — це,
// за документацією самої стратегії, «загашена пружина, яка приходить до цілі
// без стрибка», тобто саме згладжування, тільки записане так, що воно ламається
// від частоти кадрів.

// Частка шляху до цілі, яку камера долає за `dtMs`.
//
// Окремою функцією, бо це єдине місце, де живе незалежність від частоти
// кадрів, і перевіряти її треба без рушія й без браузера.
export function followFraction(dtMs, ratePerSec) {
  if (!(dtMs > 0)) return 0
  return 1 - Math.exp(-ratePerSec * (dtMs / 1000))
}

// Нова позиція фокуса камери по одній осі.
export function followAxis(focus, target, dtMs, ratePerSec) {
  return focus + (target - focus) * followFraction(dtMs, ratePerSec)
}
