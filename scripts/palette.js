// ── Кольори, що ЩОСЬ ЗНАЧАТЬ (Стадія 15 / П1) ───────────────────────────────
//
// Спільна палітра `P` вище — меблевий набір Стадії 6: дерево, тканина, метал,
// листя. Її досить для всього, що стоїть у кімнаті, і зовсім недосить для
// того, що мусить ВІДРІЗНЯТИСЬ.
//
// Це з'ясувалось вимірюванням, а не з принципу. Прогін набору через
// квантизацію в саму лише `P` показав: гоночний дрон втрачає бірюзу — а вона і
// є те, чим він відрізняється від міні на сцені; кінематографічний із сірого
// стає фіолетовим і зливається з міні; гравець міняє колір куртки, тобто стає
// іншим персонажем. Винна не квантизація: у `P` фізично немає ролей «акцент
// типу продукту» і «ліврея персонажа», тому найближчий колір і виявляється
// чужим.
//
// Тому палітра доросла до ролей, які арт уже виконував літералами в
// draw-функціях. Правило розділу просте:
//
//   якщо колір НЕСЕ ІНФОРМАЦІЮ (який це дрон, хто ця людина, що зараз
//   світиться) — він має ім'я тут і квантизація його не чіпає;
//   якщо колір — це просто відтінок реквізиту, він притягується до `P`.

