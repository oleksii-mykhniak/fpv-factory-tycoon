// Повний набір, у який квантизує `finish()`. Порядок значення не має —
// шукається найближчий.
export function fullPalette(roles = []) {
  const flat = (o) => Object.values(o).flatMap(v =>
    Array.isArray(v) ? [v] : Object.values(v).filter(Array.isArray))
  return [
    ...Object.values(P),
    ...flat(PRODUCT), ...flat(LIVERY), ...Object.values(PROP),
    ...Object.values(SIGNAL), ...Object.values(ACCENT),
    ...roles,
  ]
}
