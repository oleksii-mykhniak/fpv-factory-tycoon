// Палітра арту — одне місце, де живуть кольори гри (Стадія 13 / А5.2).
//
// Раніше вони були розсипані по функціях генератора, і жоден не можна було
// змінити в одному місці: «зробити дерево тепліше» означало знайти всі
// входження трьох байтів.
//
// Три групи, і межа між ними несуча:
//
//   P       — спільна палітра V6. З неї малюється все, що з'явилось після
//             Стадії 6, і саме вона робить набір ОДНИМ набором, а не тридцятьма
//             окремими малюнками.
//   ACCENT  — акценти з таблиці в `docs/asset_specs.md`. Це кольори, які щось
//             ЗНАЧАТЬ: нагрів, «готово». Тест звіряє їх із документом.
//   SPEC    — решта таблиці з `docs/asset_specs.md`: кольори кімнати, дрона,
//             металу. Тримаються тут, щоб документ і код не розійшлись мовчки.
//
// Кольори — трійки [r, g, b], бо саме так їх приймають примітиви малювання.

export const hex = (s) => [
  parseInt(s.slice(1, 3), 16), parseInt(s.slice(3, 5), 16), parseInt(s.slice(5, 7), 16),
]

// Один світ, одне світло, одна щільність пікселя.
//
// Це не дисципліна, це арифметика: кожен спрайт оголошує розмір у СВІТОВИХ
// одиницях (через `u()` з гри), а генератор виводить піксельний. Саме це
// правило зламав експеримент із Kenney: їхні меблі малювались під персонажа
// 16 px, наш — 64 px, тож та сама фізична річ приїжджала з пікселем учетверо
// більшим (CREDITS.md).
